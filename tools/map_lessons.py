# Parse [MM:SS.xx - MM:SS.xx] segments
pattern = r'\[(\d+:\d+\.\d+) - (\d+:\d+\.\d+)\]\s*\(SPEAKER_\d+\)\s*(.*?)(?=\[\d+:\d+\.\d+ - \d+:\d+\.\d+\]|$)'
segments = re.findall(pattern, text, re.DOTALL)

